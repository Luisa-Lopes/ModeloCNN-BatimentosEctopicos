
function [rPeaks, predictedTypes, predictedLabels] = CNN_Classifica_Paciente(patientId)

% CNN_Classifica_Paciente
%
% Carrega o ECG de um paciente, extrai os batimentos a partir
% das anotacoes dos picos R e classifica cada batimento utilizando
% uma CNN previamente treinada.
%
% Classes:
%   0 -> Normal
%   1 -> Ectopico
%
% Visualizacao:
%   - ECG completo
%   - 10 batimentos por vez
%   - Batimentos normais em verde
%   - Batimentos ectopicos em vermelho
%   - Botoes Anterior e Proximo
%   - Navegacao horizontal utilizando a barra de rolagem

%% ================================================================
% 1. Validacao do ID do paciente
% =================================================================

if ~isnumeric(patientId) || ~isscalar(patientId) || ...
        ~isfinite(patientId) || patientId ~= fix(patientId)

    error('O ID do paciente deve ser um numero inteiro.');

end

%% ================================================================
% 2. Localizacao dos arquivos
% =================================================================

scriptDir = fileparts(mfilename('fullpath'));

modelPath = fullfile( ...
    scriptDir, ...
    'CNN_Ectopic_InterPatient.mat');

subjectsDir = fullfile( ...
    fileparts(scriptDir), ...
    'SujeitosMat');

patientPath = fullfile( ...
    subjectsDir, ...
    sprintf('%d.mat', patientId));

%% ================================================================
% 3. Verificacao dos arquivos
% =================================================================

if ~isfile(modelPath)

    error( ...
        'Modelo nao encontrado em: %s', ...
        modelPath);

end

if ~isfile(patientPath)

    error( ...
        'Arquivo do paciente nao encontrado: %s', ...
        patientPath);

end

%% ================================================================
% 4. Carregamento do modelo
% =================================================================

model = load(modelPath, ...
    'net', ...
    'classNames', ...
    'optimalThreshold', ...
    'windowBefore', ...
    'windowAfter', ...
    'inputLength');

%% ================================================================
% 5. Carregamento do paciente
% =================================================================

patientData = load( ...
    patientPath, ...
    'ecg', ...
    'ann', ...
    'Fs');

%% ================================================================
% 6. Verificacao das variaveis
% =================================================================

requiredPatientFields = {'ecg', 'ann'};

for i = 1:numel(requiredPatientFields)

    if ~isfield( ...
            patientData, ...
            requiredPatientFields{i})

        error( ...
            'O arquivo do paciente precisa conter a variavel %s.', ...
            requiredPatientFields{i});

    end

end

ecg = double(patientData.ecg(:));

rPeaks = double(patientData.ann(:));

%% ================================================================
% 7. Validacao das anotacoes
% =================================================================

if any(~isfinite(rPeaks)) || ...
        any(rPeaks ~= fix(rPeaks))

    error( ...
        'As anotacoes ann devem conter indices inteiros e finitos.');

end

%% ================================================================
% 8. Remocao de picos sem janela completa
% =================================================================

validPeak = ...
    rPeaks - model.windowBefore >= 1 & ...
    rPeaks + model.windowAfter <= numel(ecg);

rPeaks = rPeaks(validPeak);

if isempty(rPeaks)

    error( ...
        'Nenhum batimento completo encontrado dentro dos limites do sinal.');

end

%% ================================================================
% 9. Extracao dos batimentos
% =================================================================

numBeats = numel(rPeaks);

beats = zeros( ...
    numBeats, ...
    model.inputLength);

for i = 1:numBeats

    firstSample = ...
        rPeaks(i) - model.windowBefore;

    lastSample = ...
        rPeaks(i) + model.windowAfter;

    beats(i, :) = ...
        ecg(firstSample:lastSample).';

end

%% ================================================================
% 10. Verificacao do tamanho
% =================================================================

if size(beats, 2) ~= model.inputLength

    error( ...
        ['O tamanho dos batimentos nao corresponde ' ...
         'a entrada esperada pela rede.']);

end

%% ================================================================
% 11. Preparacao da entrada da CNN
% =================================================================

X = reshape( ...
    beats.', ...
    [model.inputLength, 1, 1, numBeats]);

%% ================================================================
% 12. Classificacao pela CNN
% =================================================================

[~, scores] = classify( ...
    model.net, ...
    X);

%% ================================================================
% 13. Identificacao da classe Ectopic
% =================================================================

ectopicClassIndex = find( ...
    strcmp(model.classNames, 'Ectopic'), ...
    1);

if isempty(ectopicClassIndex)

    error( ...
        'A classe Ectopic nao foi encontrada no modelo salvo.');

end

%% ================================================================
% 14. Classificacao dos batimentos
% =================================================================

predictedTypes = categorical( ...
    repmat({'Normal'}, numBeats, 1), ...
    model.classNames);

predictedTypes( ...
    scores(:, ectopicClassIndex) >= ...
    model.optimalThreshold) = 'Ectopic';

%% ================================================================
% 15. Conversao para 0 e 1
% =================================================================

predictedLabels = zeros( ...
    numBeats, ...
    1);

predictedLabels( ...
    predictedTypes == 'Ectopic') = 1;

%% ================================================================
% 16. Informacoes no Command Window
% =================================================================

numNormal = sum( ...
    predictedLabels == 0);

numEctopic = sum( ...
    predictedLabels == 1);

fprintf('\n');
fprintf('=============================================\n');
fprintf('       CLASSIFICACAO DO PACIENTE\n');
fprintf('=============================================\n');
fprintf('Paciente: %d\n', patientId);
fprintf('Total de batimentos: %d\n', numBeats);
fprintf('Normal: %d\n', numNormal);
fprintf('Ectopico: %d\n', numEctopic);
fprintf('=============================================\n');
fprintf('\n');

%% ================================================================
% 17. Eixo X
% =================================================================

if isfield(patientData, 'Fs') && ...
        isscalar(patientData.Fs) && ...
        isfinite(patientData.Fs) && ...
        patientData.Fs > 0

    Fs = double(patientData.Fs);

    x = ...
        (0:numel(ecg)-1).' / Fs;

    xLabel = 'Tempo (s)';

else

    x = ...
        (1:numel(ecg)).';

    xLabel = 'Amostras';

end

%% ================================================================
% 18. Configuracao da janela
% =================================================================

% Numero de batimentos mostrados simultaneamente
visibleBeats = 10;

% Primeiro grupo de batimentos
currentStart = 1;

% Ultimo inicio possivel da janela
maxStart = max( ...
    1, ...
    numBeats - visibleBeats + 1);

%% ================================================================
% 19. Criacao da interface
% =================================================================

fig = uifigure( ...
    'Name', ...
    sprintf( ...
        'ECG - Paciente %d', ...
        patientId), ...
    'Position', ...
    [100 100 1250 750]);

%% ================================================================
% 20. Criacao dos eixos
% =================================================================

ax = uiaxes( ...
    fig, ...
    'Position', ...
    [70 210 1120 470]);

ax.Box = 'on';

grid(ax, 'on');

xlabel(ax, xLabel);

ylabel(ax, 'Amplitude do ECG');

%% ================================================================
% 21. Botoes
% =================================================================

btnPrevious = uibutton( ...
    fig, ...
    'push', ...
    'Position', ...
    [300 120 150 40], ...
    'Text', ...
    '<< Anterior');

btnNext = uibutton( ...
    fig, ...
    'push', ...
    'Position', ...
    [800 120 150 40], ...
    'Text', ...
    'Proximo >>');

%% ================================================================
% 22. Indicador da janela atual
% =================================================================

lblPosition = uilabel( ...
    fig, ...
    'Position', ...
    [450 120 350 40], ...
    'HorizontalAlignment', ...
    'center', ...
    'FontSize', ...
    14, ...
    'FontWeight', ...
    'bold');

%% ================================================================
% 23. Barra de rolagem horizontal
% =================================================================

scroll = uislider( ...
    fig, ...
    'Position', ...
    [150 80 950 3], ...
    'Limits', ...
    [1 maxStart], ...
    'Value', ...
    currentStart);

%% ================================================================
% 24. Texto da barra
% =================================================================

uilabel( ...
    fig, ...
    'Position', ...
    [150 45 950 25], ...
    'Text', ...
    'Arraste a barra para navegar pelos batimentos', ...
    'HorizontalAlignment', ...
    'center');

%% ================================================================
% 25. Atualizacao do grafico
% =================================================================

function updatePlot(startBeat)

    % Garante que o indice esteja dentro dos limites
    startBeat = round(startBeat);

    startBeat = max( ...
        1, ...
        min(startBeat, maxStart));

    currentStart = startBeat;

    % Ultimo batimento mostrado
    endBeat = min( ...
        startBeat + visibleBeats - 1, ...
        numBeats);

    % -------------------------------------------------------------
    % Intervalo de amostras
    % -------------------------------------------------------------

    firstSample = max( ...
        1, ...
        rPeaks(startBeat) - model.windowBefore);

    lastSample = min( ...
        numel(ecg), ...
        rPeaks(endBeat) + model.windowAfter);

    % -------------------------------------------------------------
    % Limpa o grafico
    % -------------------------------------------------------------

    cla(ax);

    hold(ax, 'on');

    % -------------------------------------------------------------
    % ECG
    % -------------------------------------------------------------

    plot( ...
        ax, ...
        x(firstSample:lastSample), ...
        ecg(firstSample:lastSample), ...
        'k', ...
        'LineWidth', ...
        1);

    % -------------------------------------------------------------
    % Batimentos normais
    % -------------------------------------------------------------

    normalIndices = startBeat:endBeat;

    normalIndices = normalIndices( ...
        predictedLabels(normalIndices) == 0);

    if ~isempty(normalIndices)

        plot( ...
            ax, ...
            x(rPeaks(normalIndices)), ...
            ecg(rPeaks(normalIndices)), ...
            'o', ...
            'MarkerFaceColor', ...
            'g', ...
            'MarkerEdgeColor', ...
            'g', ...
            'MarkerSize', ...
            8);

    end

    % -------------------------------------------------------------
    % Batimentos ectopicos
    % -------------------------------------------------------------

    ectopicIndices = startBeat:endBeat;

    ectopicIndices = ectopicIndices( ...
        predictedLabels(ectopicIndices) == 1);

    if ~isempty(ectopicIndices)

        plot( ...
            ax, ...
            x(rPeaks(ectopicIndices)), ...
            ecg(rPeaks(ectopicIndices)), ...
            'o', ...
            'MarkerFaceColor', ...
            'r', ...
            'MarkerEdgeColor', ...
            'r', ...
            'MarkerSize', ...
            8);

    end

    % -------------------------------------------------------------
    % Textos 0 e 1
    % -------------------------------------------------------------

    localSignal = ...
        ecg(firstSample:lastSample);

    labelOffset = ...
        max(range(localSignal) * 0.06, eps);

    for i = startBeat:endBeat

        if predictedLabels(i) == 1

            text( ...
                ax, ...
                x(rPeaks(i)), ...
                ecg(rPeaks(i)) + labelOffset, ...
                '1', ...
                'HorizontalAlignment', ...
                'center', ...
                'VerticalAlignment', ...
                'bottom', ...
                'FontSize', ...
                11, ...
                'FontWeight', ...
                'bold', ...
                'Color', ...
                'r');

        else

            text( ...
                ax, ...
                x(rPeaks(i)), ...
                ecg(rPeaks(i)) + labelOffset, ...
                '0', ...
                'HorizontalAlignment', ...
                'center', ...
                'VerticalAlignment', ...
                'bottom', ...
                'FontSize', ...
                11, ...
                'FontWeight', ...
                'bold', ...
                'Color', ...
                'g');

        end

    end

    % -------------------------------------------------------------
    % Limites
    % -------------------------------------------------------------

    xlim( ...
        ax, ...
        [x(firstSample), x(lastSample)]);

    ylim( ...
        ax, ...
        [ ...
        min(localSignal) - labelOffset, ...
        max(localSignal) + 3 * labelOffset ...
        ]);

    % -------------------------------------------------------------
    % Titulo
    % -------------------------------------------------------------

    title( ...
        ax, ...
        sprintf( ...
        'ECG do paciente %d - CNN', ...
        patientId));

    % -------------------------------------------------------------
    % Legenda
    % -------------------------------------------------------------

    legend( ...
        ax, ...
        {'ECG', 'Normal (0)', 'Ectopico (1)'}, ...
        'Location', ...
        'best');

    % -------------------------------------------------------------
    % Atualiza contador
    % -------------------------------------------------------------

    lblPosition.Text = sprintf( ...
        'Batimentos %d - %d de %d', ...
        startBeat, ...
        endBeat, ...
        numBeats);

    % -------------------------------------------------------------
    % Atualiza barra
    % -------------------------------------------------------------

    scroll.Value = startBeat;

    hold(ax, 'off');

end

%% ================================================================
% 26. Botao Anterior
% =================================================================

btnPrevious.ButtonPushedFcn = @(src, event) ...
    movePrevious();

function movePrevious()

    newStart = ...
        currentStart - visibleBeats;

    newStart = max( ...
        1, ...
        newStart);

    updatePlot(newStart);

end

%% ================================================================
% 27. Botao Proximo
% =================================================================

btnNext.ButtonPushedFcn = @(src, event) ...
    moveNext();

function moveNext()

    newStart = ...
        currentStart + visibleBeats;

    newStart = min( ...
        maxStart, ...
        newStart);

    updatePlot(newStart);

end

%% ================================================================
% 28. Barra de rolagem
% =================================================================

scroll.ValueChangedFcn = @(src, event) ...
    updatePlot(src.Value);

%% ================================================================
% 29. Primeira visualizacao
% =================================================================

updatePlot(1);

end
